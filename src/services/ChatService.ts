import type { ChatProvider, Message } from '../types/chat';

/** Explicitly selected demo provider for interface development. */
export class ChatService implements ChatProvider {
  readonly mode = 'demo' as const;
  async *stream(messages: readonly Message[], signal: AbortSignal): AsyncIterable<string> {
    const question = messages.filter(m => m.role === 'user').at(-1)?.content.toLowerCase() ?? '';
    const answer = this.answer(question);
    for (const part of answer.match(/\S+\s*/g) ?? []) {
      signal.throwIfAborted();
      await this.delay(32, signal);
      yield part;
    }
  }

  private delay(ms: number, signal: AbortSignal): Promise<void> {
    return new Promise((resolve, reject) => {
      signal.throwIfAborted();
      const abort = () => {
        clearTimeout(timer);
        reject(new DOMException('Stopped', 'AbortError'));
      };
      const timer = setTimeout(() => {
        signal.removeEventListener('abort', abort);
        resolve();
      }, ms);
      signal.addEventListener('abort', abort, { once: true });
    });
  }

  private answer(question: string): string {
    if (/газ|запах|дым|искр|теч[её]т.*кот[её]л/.test(question)) {
      return 'Это демонстрационный ответ, а не диагностика.\n\nЕсли есть запах газа, дым или искрение, прекратите эксплуатацию оборудования и обратитесь в аварийную службу. Не пытайтесь разбирать или ремонтировать его самостоятельно.\n\nВ рабочей версии помощник будет учитывать инструкции производителя и уточнять обстоятельства.';
    }
    if (/фитинг|труб|сшит|полипроп|металлопласт/.test(question)) {
      return 'Для подбора соединения сначала нужны данные о трубе. Один диаметр ещё не означает совместимость.\n\n1. Какой материал трубы: PEX, PE-RT, полипропилен или металлопластик?\n2. Какая маркировка, наружный диаметр и толщина стенки?\n3. Кто производитель трубы и где будет соединение: открыто или внутри конструкции?\n\nЭто пример ответа. После подключения модели и базы знаний здесь будет подбор по документации производителя.';
    }
    if (/холод|не гре|радиатор|батаре/.test(question)) {
      return 'Давайте уточним, как проявляется проблема.\n\n1. Не греет один радиатор или все?\n2. Радиатор полностью холодный или прогревается только часть?\n3. Трубы подачи и обратки тёплые?\n4. Когда появилась проблема: после монтажа, обслуживания или во время обычной работы?\n\nПока это демонстрационный сценарий: причина неисправности не определена. Не разбирайте горячую систему под давлением.';
    }
    if (/давлен|манометр/.test(question)) {
      return 'Чтобы обсудить изменение давления, нужны сведения о системе.\n\nУкажите модель котла, показания манометра на холодной и прогретой системе, а также как быстро меняется давление. Есть ли видимые следы воды или сообщение об ошибке?\n\nДопустимое давление нужно сверять с руководством конкретного оборудования. Это демонстрационный ответ; реальная диагностика пока не подключена.';
    }
    if (/т[её]пл.*пол|монтаж|установ|подключ/.test(question)) {
      return 'Начнём с исходных данных для монтажа.\n\n1. Это квартира или частный дом?\n2. Какой источник тепла и тип системы?\n3. Что требуется установить и какая площадь помещения?\n4. Есть ли проект и модели оборудования?\n\nПо этим данным рабочая версия помощника сможет найти подходящие инструкции и объяснить последовательность работ. Сейчас вы видите тестовый ответ для проверки интерфейса.';
    }
    return 'Помогу разобраться с вопросом по отоплению. Расскажите, какое у вас оборудование и что нужно сделать: подобрать комплектующие, спланировать монтаж или разобраться с неисправностью.\n\nЕсли есть проблема, укажите модель оборудования, симптомы и когда они появились.\n\nСейчас включён демонстрационный режим: ответы подготовлены заранее. Локальную нейросеть и базу инструкций подключим следующим этапом.';
  }
}
